
module.exports = async function handler(req, res) {
  // Разрешаем запросы с любого источника (можно сузить до своего домена Framer)
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
 
  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Только POST-запросы' });
  }
 
  const { question, context } = req.body || {};
  if (!question || typeof question !== 'string') {
    return res.status(400).json({ error: 'Нужно поле question' });
  }
 
  const projectKnowledge = `О проекте Arallith:
Arallith — проект по восстановлению пустыни Аралкум (бывшее дно Аральского моря) методом биоцементации по технологии EICP (ферментативное осаждение карбоната кальция на соевой уреазе). Состав раствора: дистиллированная вода, карбамид (мочевина), уреаза, полученная из соевых бобов (SCU), хлорид кальция (CaCl₂), буферный раствор для поддержания оптимального pH, и биостимулятор (экстракт морских водорослей или гумат калия) — он способствует развитию корневой системы саксаула после формирования корки. Химически: уреаза расщепляет карбамид, высвобождается карбонат, который с хлоридом кальция осаждает кристаллы CaCO₃ в точках контакта песчинок — это и склеивает песок в прочную корку.
 
Раствор нельзя просто распылять в воздух: на ветру Аралкума это резко снижает концентрацию и даёт неравномерную, рыхлую корку. Поэтому наземные роботы под управлением ИИ подают раствор защищённым от ветра способом прямо в песок, пропитывая верхний слой на 1-3 см, а сразу за этим прикатывают участок тяжёлым барабаном. Прикатка решает сразу три задачи: уплотняет рыхлый песок, увеличивая число контактов между песчинками для более прочной корки; вдавливает раствор на нужную глубину вместо испарения с поверхности на жаре; и формирует ровную поверхность, устойчивую к ветру и удобную для последующей посадки саксаула. Тяжёлый барабан заодно служит балластом, который удерживает лёгкого робота от сноса ветром. Роботы сами прокладывают маршрут по стратегии покрытия и приоритетно направляются к активным штормовым зонам; каждый обработанный участок фиксируется на карте и отслеживается.
 
О самом Аралкуме и Аральском море:
Аральское море начало высыхать с 1960-х годов из-за масштабного отвода воды рек Амударья и Сырдарья на орошение хлопковых полей (площадь орошения выросла с 4,5 до более 7 млн га). К 1987 году море разделилось на Северное (Малое) и Южное (Большое). В 2005 году в Казахстане достроили Кокаральскую плотину — с тех пор Северный Арал частично восстановился (+12 м уровня воды к 2008 году, рыболовство снова стало жизнеспособным к 2013 году). Южный Арал продолжает высыхать, так как Узбекистан всё ещё использует воды Амударьи для орошения. В 2014 году спутники NASA впервые зафиксировали полное пересыхание восточной части Южного Арала. Сегодня от исторического объёма моря осталось около 10%.
 
Масштаб и последствия:
Аралкум занимает около 5,5-6 млн гектаров — это самая молодая пустыня в мире. Ветер поднимает с её дна около 100 млн тонн токсичной соли и пыли ежегодно; эту пыль фиксировали в лесах Беларуси и Норвегии, в ледниках Гренландии, а следы пестицидов из региона находили даже в крови пингвинов в Антарктиде. Последствия для людей: рост респираторных заболеваний, анемии, болезней почек у жителей Приаралья (Каракалпакстан в Узбекистане, Кызылординская область в Казахстане); свыше 40 000 человек лишились работы после краха рыболовной отрасли. Изменился и микроклимат региона — лето стало жарче, зима холоднее.
 
Отвечай кратко, по-русски, только по теме проекта Arallith и Аралкум. Если не знаешь точного ответа — так и скажи, не выдумывай цифры.`;
 
  const systemPrompt = `Ты — ИИ-ассистент панели мониторинга проекта Arallith.
 
${projectKnowledge}
 
Текущие оперативные данные панели (могут меняться от запроса к запросу):
${context || 'нет данных'}`;
 
  try {
    const response = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${process.env.OPENAI_API_KEY}`,
      },
      body: JSON.stringify({
        model: 'gpt-4o-mini',
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: question },
        ],
        max_tokens: 350,
        temperature: 0.4,
      }),
    });
 
    const data = await response.json();
 
    if (!response.ok) {
      console.error('OpenAI error:', data);
      return res.status(502).json({ error: 'Ошибка модели' });
    }
 
    const answer = data.choices?.[0]?.message?.content?.trim() || 'Не удалось получить ответ.';
    return res.status(200).json({ answer });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Внутренняя ошибка прокси' });
  }
}
 



